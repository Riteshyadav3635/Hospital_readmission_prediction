def _numeric_input(feature: str, defaults: dict[str, Any]) -> int:
    return int(
        st.number_input(
            _display_label(feature),
            min_value=0,
            value=max(0, int(defaults.get(feature, 0))),
            step=1,
            key=f"feature_{feature}",
            help=FEATURE_HELP.get(feature, f"Non-negative value for the model input {feature}."),
        )
    )


def _category_input(
    feature: str,
    options: list[str],
    default: str | None = None,
) -> str:
    if not options:
        raise ValueError(f"No trained categories are available for {feature}.")
    index = options.index(default) if default in options else 0
    return st.selectbox(
        _display_label(feature),
        options=options,
        index=index,
        key=f"feature_{feature}",
        help=FEATURE_HELP.get(feature, f"Select a value accepted by the saved model for {feature}."),
    )


def collect_model_inputs(bundle: dict[str, Any]) -> dict[str, Any]:
    """Render approachable groups while honoring the saved scaler's exact feature contract."""
    feature_columns = bundle["feature_columns"]
    encoders = bundle["encoders"]
    defaults = default_inputs(encoders)
    values: dict[str, Any] = {}
    rendered: set[str] = set()

    st.caption(
        f"Provide all {len(feature_columns)} model inputs. Choices for encoded fields "
        "come from the fitted training encoders."
    )

    def render_features(features: list[str], width: int = 2) -> None:
        columns = st.columns(width)
        for index, feature in enumerate(features):
            with columns[index % width]:
                if feature in LABEL_ENCODED_FEATURES:
                    options = [str(value) for value in encoders[feature].classes_]
                    values[feature] = _category_input(feature, options, defaults.get(feature))
                elif feature == "age":
                    values[feature] = _category_input(feature, list(AGE_MAPPING), defaults.get(feature))
                elif feature == "gender":
                    values[feature] = _category_input(feature, list(GENDER_MAPPING), defaults.get(feature))
                elif feature in MEDICATION_FEATURES:
                    values[feature] = _category_input(feature, list(MEDICATION_MAPPING), defaults[feature])
                elif feature == "change":
                    values[feature] = _category_input(feature, list(CHANGE_MAPPING), defaults[feature])
                elif feature == "diabetesMed":
                    values[feature] = _category_input(feature, list(BINARY_MAPPING), defaults[feature])
                else:
                    values[feature] = _numeric_input(feature, defaults)
                rendered.add(feature)

    st.markdown("#### Patient information")
    render_features([name for name in ("race", "gender", "age") if name in feature_columns], 3)

    st.markdown("#### Admission information")
    admission_features = [name for name in ("admission_type_id", "admission_source_id", "discharge_disposition_id", "time_in_hospital") if name in feature_columns]
    render_features(admission_features, 4)

    st.markdown("#### Hospital utilization")
    utilization_features = [name for name in ("num_lab_procedures", "num_procedures", "num_medications", "number_outpatient", "number_emergency", "number_inpatient") if name in feature_columns]
    render_features(utilization_features, 3)

    st.markdown("#### Clinical information")
    clinical_features = [name for name in ("medical_specialty", "diag_1", "diag_2", "diag_3", "number_diagnoses") if name in feature_columns]
    render_features(clinical_features, 3)

    medication_features = [feature for feature in feature_columns if feature in MEDICATION_FEATURES or feature in ("change", "diabetesMed")]
    if medication_features:
        with st.expander("Medication and treatment details", expanded=False):
            render_features(medication_features, 3)

    # Keep future artifact features visible and usable rather than silently omitting them.
    remaining_features = [feature for feature in feature_columns if feature not in rendered]
    if remaining_features:
        with st.expander("Additional model features", expanded=False):
            render_features(remaining_features, 3)

    with st.expander("Model input contract", expanded=False):
        st.dataframe(
            pd.DataFrame({"Feature": feature_columns, "Input type": ["Categorical" if feature in LABEL_ENCODED_FEATURES or feature in MEDICATION_FEATURES or feature in ("age", "gender", "change", "diabetesMed") else "Non-negative integer" for feature in feature_columns]}),
            hide_index=True,
            width="stretch",
        )
    return values


def render_prediction(bundle: dict[str, Any] | None) -> None:
    _render_header(
        "Saved model · Inference",
        "Predict readmission",
        "Review encounter inputs, then run the saved encoders, scaler, PCA transform, and Logistic Regression model.",
    )
    st.warning(DISCLAIMER)
    if bundle is None:
        return

    input_values = collect_model_inputs(bundle)
    st.markdown("### Review patient information")
    summary = st.container(border=True)
    with summary:
        summary_columns = st.columns(5)
        summary_items = [
            ("Age", input_values.get("age", "Unavailable")),
            ("Admission type", input_values.get("admission_type_id", "Unavailable")),
            ("Diagnoses", input_values.get("number_diagnoses", "Unavailable")),
            ("Medications", input_values.get("num_medications", "Unavailable")),
            ("Previous utilization", f"Inpatient {input_values.get('number_inpatient', 0)} · ER {input_values.get('number_emergency', 0)} · Outpatient {input_values.get('number_outpatient', 0)}"),
        ]
        for column, (label, value) in zip(summary_columns, summary_items):
            column.metric(label, str(value))

    submitted = st.button("Generate Prediction", type="primary", width="stretch", key="generate_prediction")
    if submitted:
        try:
            with st.spinner("Analyzing patient information..."):
                result = predict(input_values)
        except (ValueError, KeyError, TypeError) as error:
            st.error(f"Input could not be processed: {error}")
            return
        except Exception:
            LOGGER.exception("Prediction failed")
            st.error("The prediction could not be completed. Review the values and try again.")
            return

        record = make_history_record(result)
        try:
            append_prediction_history(record)
        except OSError:
            LOGGER.exception("Could not save prediction outcome to local history")
            st.warning("The estimate was generated, but local prediction history could not be saved.")

        st.markdown("### Prediction result")
        prediction_label = "Readmitted within 30 days" if result["prediction"] == 1 else "Not readmitted within 30 days"
        with st.container(border=True):
            result_columns = st.columns(3)
            result_columns[0].metric("Prediction", prediction_label)
            if result["probability"] is not None:
                result_columns[1].metric(
                    "Estimated probability for class 1",
                    f"{result['probability']:.1%}",
                    help="This is the classifier's probability estimate, not a calibrated clinical risk score.",
                )
            result_columns[2].metric("Model output", f"Class {result['prediction']}")
            st.caption(result["explanation"])
        st.info(DISCLAIMER)
        result_download = pd.DataFrame([record]).to_csv(index=False).encode("utf-8")
        st.download_button(
            "Download this result as CSV",
            data=result_download,
            file_name="readmission_prediction.csv",
            mime="text/csv",
        )
        if st.button("New Prediction", key="new_prediction"):
            st.rerun()

