def _render_filters(data: pd.DataFrame, key_prefix: str) -> pd.DataFrame:
    st.markdown("#### Filter encounter records")
    columns = st.columns(5)

    ages = [value for value in AGE_MAPPING if value in set(data.get("age", []))]
    genders = sorted(data["gender"].dropna().astype(str).unique().tolist())
    admission_types = sorted(data["admission_type_id"].dropna().unique().tolist())
    specialties = sorted(data["medical_specialty"].dropna().astype(str).unique().tolist())
    statuses = [label for label in TARGET_LABELS.values() if label in _target_status(data[TARGET_COLUMN]).unique()]

    with columns[0]:
        age_filter = st.selectbox("Age group", ["All"] + ages, key=f"{key_prefix}_age")
    with columns[1]:
        gender_filter = st.selectbox("Gender", ["All"] + genders, key=f"{key_prefix}_gender")
    with columns[2]:
        admission_filter = st.selectbox(
            "Admission type",
            ["All"] + [str(value) for value in admission_types],
            key=f"{key_prefix}_admission",
        )
    with columns[3]:
        specialty_filter = st.selectbox(
            "Medical specialty", ["All"] + specialties, key=f"{key_prefix}_specialty"
        )
    with columns[4]:
        status_filter = st.selectbox(
            "Readmission status", ["All"] + statuses, key=f"{key_prefix}_status"
        )

    filtered = data.copy()
    if age_filter != "All":
        filtered = filtered.loc[filtered["age"] == age_filter]
    if gender_filter != "All":
        filtered = filtered.loc[filtered["gender"].astype(str) == gender_filter]
    if admission_filter != "All":
        filtered = filtered.loc[
            filtered["admission_type_id"].astype(str) == admission_filter
        ]
    if specialty_filter != "All":
        filtered = filtered.loc[
            filtered["medical_specialty"].astype(str) == specialty_filter
        ]
    if status_filter != "All":
        filtered = filtered.loc[_target_status(filtered[TARGET_COLUMN]) == status_filter]
    st.caption(f"Showing {len(filtered):,} of {len(data):,} encounters")
    return filtered


def _counts(data: pd.DataFrame, column: str, order: list[str] | None = None) -> pd.DataFrame:
    counts = data[column].fillna("Missing").astype(str).value_counts()
    if order is not None:
        counts = counts.reindex(order, fill_value=0)
    return counts.rename("Encounters").rename_axis("Category").reset_index()


