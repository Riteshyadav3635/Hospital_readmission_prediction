def _plotly_layout(figure: Any, *, height: int = 320) -> Any:
    figure.update_layout(
        height=height,
        margin={"l": 10, "r": 12, "t": 22, "b": 12},
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(0,0,0,0)",
        font={"family": "sans-serif", "color": "#435763"},
        legend_title_text="",
        colorway=PLOTLY_COLORS,
        hoverlabel={"bgcolor": "#ffffff", "font_size": 13},
    )
    figure.update_xaxes(showgrid=False, linecolor="#dce6eb", automargin=True)
    figure.update_yaxes(gridcolor="#edf2f4", zeroline=False, automargin=True)
    return figure


def _show_plotly(figure: Any, description: str, *, height: int = 320) -> None:
    st.plotly_chart(
        _plotly_layout(figure, height=height),
        use_container_width=True,
        config=PLOTLY_CONFIG,
        key=f"chart_{description.lower().replace(' ', '_')}",
        theme="streamlit",
    )


