def render_dataset_explorer(data: pd.DataFrame | None) -> None:
    _render_header(
        "Bundled data · Privacy-aware preview",
        "Dataset explorer",
        "Explore the bundled diabetic inpatient encounter CSV. Source identifiers are excluded from this view and from exported tables.",
    )
    if data is None:
        return
    display_data = _dataset_for_display(data)
    metrics = st.columns(4)
    metrics[0].metric("Rows", f"{len(data):,}")
    metrics[1].metric("Source columns", f"{data.shape[1]}")
    metrics[2].metric("Displayed columns", f"{display_data.shape[1]}")
    metrics[3].metric("Missing cells", f"{int(display_data.isna().sum().sum()):,}")

    with st.expander("Column details", expanded=False):
        details = pd.DataFrame(
            {
                "Column": display_data.columns,
                "Data type": display_data.dtypes.astype(str).values,
                "Missing values": display_data.isna().sum().values,
                "Unique values": display_data.nunique(dropna=True).values,
            }
        )
        st.dataframe(details, hide_index=True, width="stretch", height=450)
        st.markdown("#### Numeric summary")
        st.dataframe(display_data.describe(include=["number"]).T, width="stretch")

    filtered = _render_filters(data, "explorer")
    safe_filtered = _dataset_for_display(filtered)
    search_columns = ["None"] + list(safe_filtered.columns)
    search_controls = st.columns([1, 2, 1])
    with search_controls[0]:
        search_column = st.selectbox("Search column", search_columns, key="explorer_search_column")
    with search_controls[1]:
        search_text = st.text_input("Contains text", key="explorer_search_text")
    if search_column != "None" and search_text:
        mask = safe_filtered[search_column].astype("string").str.contains(
            search_text, case=False, regex=False, na=False
        )
        safe_filtered = safe_filtered.loc[mask]
    with search_controls[2]:
        page_size = st.selectbox("Rows per page", [25, 50, 100, 250], index=1)

    st.caption(f"{len(safe_filtered):,} rows match the current filters and search.")
    page_count = max(1, (len(safe_filtered) + page_size - 1) // page_size)
    page_number = st.number_input("Table page", min_value=1, max_value=page_count, value=1, step=1)
    start = (int(page_number) - 1) * page_size
    st.dataframe(
        safe_filtered.iloc[start : start + page_size],
        hide_index=True,
        width="stretch",
        height=480,
    )
    st.download_button(
        "Download filtered dataset as CSV",
        data=safe_filtered.to_csv(index=False).encode("utf-8"),
        file_name="filtered_diabetic_encounters.csv",
        mime="text/csv",
    )


