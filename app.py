def _render_shared_filters(data: pd.DataFrame | None) -> None:
    st.sidebar.markdown("### Shared dataset filters")
    st.sidebar.caption("These filters stay in sync across Dashboard, Analytics, and Dataset Explorer.")
    if data is None:
        st.sidebar.caption("Dataset filters are unavailable.")
        return

    with st.sidebar.expander("Filter encounters", expanded=False):
        if "age" in data:
            ages = [age for age in AGE_MAPPING if age in set(data["age"].dropna())]
            st.selectbox("Age group", ["All", *ages], key="shared_age_group")
        if "gender" in data:
            genders = sorted(data["gender"].dropna().astype(str).unique().tolist())
            st.selectbox("Gender", ["All", *genders], key="shared_gender")
        if "admission_type_id" in data:
            admission_types = sorted(data["admission_type_id"].dropna().astype(str).unique().tolist())
            st.selectbox("Admission type", ["All", *admission_types], key="shared_admission_type")
        if "medical_specialty" in data:
            specialties = sorted(data["medical_specialty"].dropna().astype(str).unique().tolist())
            st.selectbox("Medical specialty", ["All", *specialties], key="shared_specialty")
        if TARGET_COLUMN in data:
            available_statuses = [label for label in TARGET_LABELS.values() if label in _target_status(data[TARGET_COLUMN]).unique()]
            st.selectbox("Readmission status", ["All", *available_statuses], key="shared_outcome")
        st.button("Reset dataset filters", on_click=_reset_shared_filters, use_container_width=True)


def _apply_shared_filters(data: pd.DataFrame | None) -> pd.DataFrame | None:
    if data is None:
        return None
    filtered = data
    choices = {key: st.session_state.get(key, "All") for key in SHARED_FILTER_KEYS}
    if choices["shared_age_group"] != "All" and "age" in filtered:
        filtered = filtered.loc[filtered["age"] == choices["shared_age_group"]]
    if choices["shared_gender"] != "All" and "gender" in filtered:
        filtered = filtered.loc[filtered["gender"].astype(str) == choices["shared_gender"]]
    if choices["shared_admission_type"] != "All" and "admission_type_id" in filtered:
        filtered = filtered.loc[filtered["admission_type_id"].astype(str) == choices["shared_admission_type"]]
    if choices["shared_specialty"] != "All" and "medical_specialty" in filtered:
        filtered = filtered.loc[filtered["medical_specialty"].astype(str) == choices["shared_specialty"]]
    if choices["shared_outcome"] != "All" and TARGET_COLUMN in filtered:
        filtered = filtered.loc[_target_status(filtered[TARGET_COLUMN]) == choices["shared_outcome"]]
    return filtered


def _shared_filter_summary(data: pd.DataFrame) -> str:
    active = any(st.session_state.get(key, "All") != "All" for key in SHARED_FILTER_KEYS)
    if active:
        return f"Showing {len(data):,} encounters matching the shared sidebar filters."
    return f"Showing all {len(data):,} encounters. Shared dataset filters are clear."


def _counts(data: pd.DataFrame, column: str, order: list[str] | None = None) -> pd.DataFrame:
    counts = data[column].fillna("Missing").astype(str).value_counts()
    if order is not None:
        counts = counts.reindex(order, fill_value=0)
    return counts.rename("Encounters").rename_axis("Category").reset_index()


def render_dashboard(data: pd.DataFrame | None, bundle: dict[str, Any] | None) -> None:
    with st.container(key="dashboard_hero"):
        hero_left, hero_right = st.columns([4, 1.2], vertical_alignment="center")
        with hero_left:
            st.caption("HOSPITAL ANALYTICS • AI INSIGHTS")
            st.title("Hospital Readmission Prediction")
            st.markdown(
                "AI-powered analysis of patient encounters and 30-day readmission risk "
                "using the project's saved machine-learning pipeline."
            )
        with hero_right:
            st.markdown('<div class="hero-emblem">✚</div>', unsafe_allow_html=True)
            st.button(
                "Start Prediction →",
                type="primary",
                width="stretch",
                key="start_prediction",
                on_click=_go_to_prediction,
            )
    _render_disclaimer()

    if data is None:
        return
    if TARGET_COLUMN not in data.columns:
        st.error(f"The dataset does not contain the expected target column: {TARGET_COLUMN}.")
        return
    if data.empty:
        st.info("No encounters match the shared filters. Reset or adjust them in the sidebar.")
        return

    early_count = int((data[TARGET_COLUMN] == "<30").sum())
    readmission_rate = early_count / len(data) if len(data) else 0.0
    patient_count = int(data["patient_nbr"].nunique(dropna=True)) if "patient_nbr" in data else len(data)
    age_midpoints = {}
    for age_group in AGE_MAPPING:
        lower, upper = age_group.strip("[]() ").split("-", maxsplit=1)
        age_midpoints[age_group] = (int(lower) + int(upper)) / 2
    average_age = data["age"].map(age_midpoints).mean() if "age" in data else float("nan")

    st.markdown("### At a glance")
    _render_kpi_cards([
        ("👥 Total patients", f"{patient_count:,}", f"Unique IDs · {len(data):,} encounters in this selection", "blue"),
        ("🔄 Readmission rate", f"{readmission_rate:.1%}", "Encounters labeled <30 days", "teal"),
        ("📅 Average age", f"{average_age:.1f} years" if pd.notna(average_age) else "Unavailable", "Approximate midpoint of age bands", "green"),
        ("⚠️ Readmission cases", f"{early_count:,}", "Observed <30-day encounters", "orange"),
    ])

    st.markdown("### Dataset overview")
    st.caption(f"{DATASET_FILE} · {data.shape[1]} source columns")
    st.caption(_shared_filter_summary(data))
    chart_left, chart_right = st.columns(2)
    distribution = _counts(data, TARGET_COLUMN, ["NO", ">30", "<30"])
    distribution["Outcome"] = distribution.pop("Category").map(TARGET_LABELS)
    with chart_left:
        st.markdown("#### Readmission distribution")
        _show_plotly(px.bar(distribution, x="Outcome", y="Encounters", color="Outcome", text_auto=True), "Encounter counts by readmission outcome")
    with chart_right:
        st.markdown("#### Age distribution")
        age_order = [age for age in AGE_MAPPING if age in set(data["age"].dropna())]
        age_counts = _counts(data, "age", age_order)
        _show_plotly(px.bar(age_counts, x="Category", y="Encounters", text_auto=True), "Encounter counts by age group")

    chart_left, chart_right = st.columns(2)
    with chart_left:
        st.markdown("#### Admission type")
        if "admission_type_id" in data:
            admission = _counts(data, "admission_type_id").sort_values("Encounters", ascending=False)
            admission["Category"] = admission["Category"].astype(str)
            _show_plotly(px.bar(admission, x="Category", y="Encounters", text_auto=True), "Encounter counts by admission type")
    with chart_right:
        st.markdown("#### Gender distribution")
        if "gender" in data:
            gender = _counts(data, "gender")
            _show_plotly(px.pie(gender, names="Category", values="Encounters", hole=.55), "Encounter distribution by gender")

    if "number_diagnoses" in data or "num_medications" in data:
        statistics_left, statistics_right = st.columns(2)
        if "number_diagnoses" in data:
            with statistics_left:
                st.markdown("#### Diagnoses per encounter")
                _show_plotly(px.histogram(data, x="number_diagnoses", nbins=10, color_discrete_sequence=[PLOTLY_COLORS[1]]), "Distribution of diagnosis counts per encounter")
        if "num_medications" in data:
            with statistics_right:
                st.markdown("#### Medications per encounter")
                _show_plotly(px.histogram(data, x="num_medications", nbins=16, color_discrete_sequence=[PLOTLY_COLORS[2]]), "Distribution of medication counts per encounter")

    if "medical_specialty" in data:
        st.markdown("#### Most represented medical specialties")
        specialty = _counts(data, "medical_specialty").head(12).sort_values("Encounters")
        _show_plotly(px.bar(specialty, x="Encounters", y="Category", orientation="h", text_auto=True), "Top medical specialties by encounter count", height=390)

    st.markdown("### Key insights")
    insight_values: list[tuple[str, str, str]] = []
