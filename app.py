def render_history() -> None:
    _render_header(
        "Local app storage · Outcomes only",
        "Prediction history",
        "History stores prediction outputs only. Submitted feature values and identifiers are not saved.",
    )
    st.info(
        "The CSV is local to this app deployment. On Community Cloud it can be shared "
        "between app visitors, and it may be cleared when the app restarts or redeploys. "
        "It is temporary demo storage, not a production medical record system."
    )

    try:
        history = load_prediction_history()
    except (OSError, pd.errors.ParserError, ValueError) as error:
        LOGGER.exception("Could not load local prediction history")
        st.error("Local prediction history could not be read.")
        with st.expander("Technical details"):
            st.code(str(error))
        return

    if history.empty:
        st.info("No predictions have been recorded yet.")
        return

    history["Timestamp (UTC)"] = pd.to_datetime(
        history["Timestamp (UTC)"], errors="coerce", utc=True
    )
    filter_columns = st.columns(3)
    predictions = ["All"] + sorted(history["Prediction"].dropna().unique().tolist())
    risks = ["All"] + sorted(history["Risk level"].dropna().unique().tolist())
    with filter_columns[0]:
        prediction_filter = st.selectbox("Prediction", predictions)
    with filter_columns[1]:
        risk_filter = st.selectbox("Model output label", risks)
    with filter_columns[2]:
        sort_order = st.selectbox("Sort by date", ["Newest first", "Oldest first"])

    filtered = history.copy()
    if prediction_filter != "All":
        filtered = filtered.loc[filtered["Prediction"] == prediction_filter]
    if risk_filter != "All":
        filtered = filtered.loc[filtered["Risk level"] == risk_filter]
    filtered = filtered.sort_values(
        "Timestamp (UTC)", ascending=(sort_order == "Oldest first"), na_position="last"
    )

    st.metric("Saved predictions", f"{len(history):,}")
    st.dataframe(filtered, hide_index=True, width="stretch")
    st.download_button(
        "Download filtered history as CSV",
        data=filtered.to_csv(index=False).encode("utf-8"),
        file_name="prediction_history.csv",
        mime="text/csv",
    )
    if st.button("Clear prediction history", type="secondary"):
        try:
            clear_prediction_history()
        except OSError as error:
            LOGGER.exception("Could not clear local prediction history")
            st.error(f"History could not be cleared: {error}")
        else:
            st.success("Prediction history cleared.")
            st.rerun()


def render_model_insights(bundle: dict[str, Any] | None) -> None:
    _render_header(
        "Saved artifacts · Pipeline",
        "Model insights",
        "Inspect the actual preprocessing and classifier artifacts used for predictions, plus evaluation results recorded in the original analysis notebook.",
    )
    if bundle is None:
        return

    model = bundle["model"]
    pca = bundle["pca"]
    st.markdown("### Inference pipeline")
    st.code(
        "Input fields → fitted label/category mappings → StandardScaler → "
        "PCA transform → LogisticRegression → class and probability",
        language="text",
    )
    cards = st.columns(4)
    cards[0].metric("Scaler input columns", f"{len(bundle['feature_columns'])}")
    cards[1].metric("PCA components", f"{pca.n_components_}")
    cards[2].metric("Fitted variance retained", f"{pca.explained_variance_ratio_.sum():.2%}")
    cards[3].metric("Prediction classes", ", ".join(map(str, model.classes_)))

    with st.expander("Exact scaler feature order", expanded=False):
        st.dataframe(
            pd.DataFrame({"Position": range(1, len(bundle["feature_columns"]) + 1), "Feature": bundle["feature_columns"]}),
            hide_index=True,
            width="stretch",
        )

    component_data = pd.DataFrame(
        {
            "Component": [f"PC{index + 1}" for index in range(len(pca.explained_variance_ratio_))],
            "Variance ratio": pca.explained_variance_ratio_,
            "Cumulative variance": pca.explained_variance_ratio_.cumsum(),
        }
    )
    st.markdown("### PCA explained variance")
    st.caption("Values below are read directly from the saved PCA artifact; PCA is not refitted by the app.")
    st.line_chart(
        component_data.set_index("Component")[["Cumulative variance"]],
        y_label="Cumulative variance ratio",
        width="stretch",
    )
    st.bar_chart(
        component_data.set_index("Component")[["Variance ratio"]],
        y_label="Variance ratio",
        use_container_width=True,
    )

    st.markdown("### Classifier")
    parameters = model.get_params()
    parameter_rows = [
        ("Estimator", type(model).__name__),
        ("Solver", parameters.get("solver")),
        ("Class weighting", parameters.get("class_weight")),
        ("C", parameters.get("C")),
        ("Maximum iterations", parameters.get("max_iter")),
        ("Random state", parameters.get("random_state")),
        ("Class 1", "Readmitted within 30 days (<30)"),
        ("Class 0", "No readmission or readmission after 30 days"),
    ]
    parameter_table = pd.DataFrame(parameter_rows, columns=["Property", "Saved value"])
    parameter_table["Saved value"] = parameter_table["Saved value"].astype("string")
    st.dataframe(parameter_table, hide_index=True, width="stretch")

    st.markdown("### Recorded evaluation results")
    st.caption(
        "These held-out results are recorded in ml/notebooks/Hospital_Readmission_Analysis.ipynb "
        "for the baseline pipeline configuration. They are not recalculated by this app."
    )
    metric_columns = st.columns(len(NOTEBOOK_METRICS))
    for column, (name, value) in zip(metric_columns, NOTEBOOK_METRICS.items()):
        column.metric(name, value)
    st.markdown("#### Notebook confusion matrix")
    st.caption("Rows are actual classes; columns are predicted classes. Class 1 means readmitted within 30 days.")
    st.dataframe(NOTEBOOK_CONFUSION, width="stretch")
    st.warning(
        "The positive-class precision is low in the notebook evaluation, and the dataset is imbalanced. "
        "These estimates are not clinically validated and should not guide care."
    )


def render_dataset_explorer(data: pd.DataFrame | None) -> None:
    _render_header(
        "Bundled data · Privacy-aware preview",
        "Dataset explorer",
        "Explore the bundled diabetic inpatient encounter CSV. Source identifiers are excluded from this view and from exported tables.",
    )
    if data is None:
        return
    display_data = _dataset_for_display(data)
    metrics = st.columns(4)
    metrics[0].metric("Rows", f"{len(data):,}")
    metrics[1].metric("Source columns", f"{data.shape[1]}")
    metrics[2].metric("Displayed columns", f"{display_data.shape[1]}")
    metrics[3].metric("Missing cells", f"{int(display_data.isna().sum().sum()):,}")

    with st.expander("Column details", expanded=False):
        details = pd.DataFrame(
            {
                "Column": display_data.columns,
                "Data type": display_data.dtypes.astype(str).values,
                "Missing values": display_data.isna().sum().values,
                "Unique values": display_data.nunique(dropna=True).values,
            }
        )
        st.dataframe(details, hide_index=True, width="stretch", height=450)
        st.markdown("#### Numeric summary")
        st.dataframe(display_data.describe(include=["number"]).T, width="stretch")

    filtered = _render_filters(data, "explorer")
    safe_filtered = _dataset_for_display(filtered)
    search_columns = ["None"] + list(safe_filtered.columns)
    search_controls = st.columns([1, 2, 1])
    with search_controls[0]:
        search_column = st.selectbox("Search column", search_columns, key="explorer_search_column")
    with search_controls[1]:
        search_text = st.text_input("Contains text", key="explorer_search_text")
    if search_column != "None" and search_text:
        mask = safe_filtered[search_column].astype("string").str.contains(
            search_text, case=False, regex=False, na=False
        )
        safe_filtered = safe_filtered.loc[mask]
    with search_controls[2]:
        page_size = st.selectbox("Rows per page", [25, 50, 100, 250], index=1)

    st.caption(f"{len(safe_filtered):,} rows match the current filters and search.")
    page_count = max(1, (len(safe_filtered) + page_size - 1) // page_size)
    page_number = st.number_input("Table page", min_value=1, max_value=page_count, value=1, step=1)
    start = (int(page_number) - 1) * page_size
    st.dataframe(
        safe_filtered.iloc[start : start + page_size],
        hide_index=True,
        width="stretch",
        height=480,
    )
    st.download_button(
        "Download filtered dataset as CSV",
        data=safe_filtered.to_csv(index=False).encode("utf-8"),
        file_name="filtered_diabetic_encounters.csv",
        mime="text/csv",
    )


