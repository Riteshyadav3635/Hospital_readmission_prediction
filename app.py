@st.cache_data(show_spinner="Loading the bundled encounter dataset…")
def load_dataset() -> pd.DataFrame:
    """Load the source CSV once; the source's '?' marker means missing."""
    if not DATA_PATH.is_file():
        raise FileNotFoundError(f"Dataset file was not found: {DATA_PATH.name}")
    return pd.read_csv(DATA_PATH, na_values=["?"], low_memory=False)


@st.cache_resource(show_spinner="Loading the saved prediction model…")
def load_cached_model_bundle() -> dict[str, Any]:
    """Cache the fitted scaler, PCA, encoders, and classifier for this app process."""
    return load_model_bundle()


def _display_label(feature: str) -> str:
    if feature in NUMERIC_LABELS:
        return NUMERIC_LABELS[feature]
    return feature.replace("-", " ").replace("_", " ").replace("Id", "ID").title()


def _target_status(series: pd.Series) -> pd.Series:
    return series.map(TARGET_LABELS).fillna("Unknown")


def _dataset_for_display(data: pd.DataFrame) -> pd.DataFrame:
    """Drop source identifiers from tables and downloads."""
    return data.drop(columns=list(IDENTIFIER_COLUMNS), errors="ignore")


def _history_or_warn() -> pd.DataFrame:
    try:
        return load_prediction_history()
    except (OSError, pd.errors.ParserError, ValueError) as error:
        LOGGER.exception("Could not read local prediction history")
        st.warning(f"Prediction history could not be read: {error}")
        return history_frame([])


